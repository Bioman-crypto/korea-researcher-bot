import re

# AI 답에 섞여 나오는 옛 용어 → 화면 용어. 프롬프트(검증 원본)는 그대로 두고 보여 주기 직전에만 바꾼다.
# AI에게 보내는 글(engine.make_record 등)에는 쓰지 않는다 — 검증한 입력 형식이 바뀌면 안 된다.
_PARTICLE_AFTER_KAN = {"을": "를", "이": "가", "은": "는", "으로": "로", "과": "와"}


def plain(text):
    s = str(text or "")
    s = s.replace("경험 단어", "경험 키워드")
    s = re.sub(r"(?<![가-힣])짝(?=(으로|을|이|은|과|마다|도|의|에|만|\s|[,.)'’\"]|$))", "조합", s)
    s = re.sub(r"한 칸(으로|을|이|은|과)?", lambda m: "한 단계" + _PARTICLE_AFTER_KAN.get(m.group(1) or "", ""), s)
    s = s.replace("코칭", "피드백")
    return s


